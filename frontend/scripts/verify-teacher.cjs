// 开发验收脚本：使用真实 Edge + 本机服务，不模拟 API。
// 需要外部安装的 playwright（可通过 NODE_PATH 提供），E2E_PASSWORD 仅从进程环境读取。
// 会保留一套 Java 演示课程/考试；临时课程和题目通过页面删除。
const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const output = path.resolve(__dirname, '../e2e-results')
const base = process.env.E2E_BASE_URL || 'http://localhost:5173'
const password = process.env.E2E_PASSWORD
if (!password) throw new Error('请通过进程环境变量 E2E_PASSWORD 提供测试账号密码')
;(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
  page.on('requestfailed', r => errors.push(r.url() + ': ' + r.failure()?.errorText))
  page.on('dialog', d => d.accept())
  const visible = async locator => { await locator.waitFor({ state: 'visible' }) }
  const heading = name => page.getByRole('heading', { name, exact: true })
  const button = name => page.getByRole('button', { name, exact: true })
  const card = name => page.locator('article.course-card').filter({ has: page.getByRole('heading', { name, exact: true }) })
  const saveModal = async name => {
    await button(name).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
  }
  async function login(username) {
    await page.goto(base + '/login')
    await page.getByLabel('用户名').fill(username)
    await page.getByLabel('密码', { exact: true }).fill(password)
    await button('登录').click()
  }
  async function createCourse(name) {
    await button('+ 创建课程').click()
    await page.getByLabel('课程名称').fill(name)
    await page.getByLabel('课程描述').fill('阶段4真实浏览器演示：课程、考试与试卷设计')
    await saveModal('保存课程')
    await visible(card(name))
  }
  async function singleQuestion(content) {
    await button('+ 添加题目').click()
    await page.getByLabel('题目内容').fill(content)
    for (const [key,text] of Object.entries({ A:'public static void main(String[] args)', B:'run()', C:'start()', D:'init()' })) {
      await page.getByLabel(key + ' 选项').fill(text)
    }
    await saveModal('保存题目')
    await visible(heading(content))
  }
  try {
    await login('teacher_demo')
    await visible(heading('教师工作台'))
    console.log('PASS teacher login and real dashboard')
    await page.getByRole('link', { name: '▤课程管理', exact: true }).click()
    await visible(heading('课程管理'))
    await createCourse('阶段4临时删除验证')
    await card('阶段4临时删除验证').getByRole('button', { name: '编辑', exact: true }).click()
    await page.getByLabel('课程名称').fill('阶段4临时编辑验证')
    await saveModal('保存课程')
    await visible(card('阶段4临时编辑验证'))
    await card('阶段4临时编辑验证').getByRole('button', { name: '删除', exact: true }).click()
    await card('阶段4临时编辑验证').waitFor({ state: 'hidden' })
    console.log('PASS course create, edit and confirmed delete')

    let courseUrl, examUrl
    if (process.env.E2E_VERIFY_EXISTING === '1') {
      // 复验模式不重新插入演示数据，只验证已发布结果。
      await visible(card('Java程序设计'))
      await card('Java程序设计').getByRole('link', {name:'进入课程'}).click()
      await visible(heading('Java程序设计'))
      courseUrl=page.url()
      await page.getByRole('link', {name:'管理考试 →'}).click()
      await visible(heading('Java基础测试'))
      examUrl=page.url()
      await visible(page.getByText(/考试已发布，关键规则和题目已锁定/))
      assert.equal(await page.locator('.question-card').count(),2)
      assert.equal(await page.locator('.question-card li').count(),3)
      assert.match(await page.locator('.workspace-content').innerText(), /共 2 题 · 总分 15 分/)
      assert.equal(await button('编辑考试').count(),0)
      await page.reload()
      await visible(heading('请说明JWT认证流程。'))
      await page.screenshot({path:path.join(output,'exam-published.png'),fullPage:true})
      console.log('PASS existing published exam, questions, points and refresh')
    } else {
    assert.equal(await card('Java程序设计').count(), 0, '已有同名演示课程，请设置 E2E_VERIFY_EXISTING=1 进行复验')
    await createCourse('Java程序设计')
    await page.reload()
    await visible(card('Java程序设计'))
    await card('Java程序设计').getByRole('link', { name:'进入课程' }).click()
    await visible(heading('Java程序设计'))
    courseUrl = page.url()
    await page.reload()
    await visible(heading('Java程序设计'))
    console.log('PASS course list/detail refresh persistence')
    await button('+ 创建考试').click()
    await page.getByLabel('考试标题').fill('Java基础测试')
    await page.getByLabel('考试说明').fill('Java 基础知识与 JWT 认证原理。总分 15 分。')
    await page.getByLabel('开始时间', { exact: true }).fill('2027-01-10T09:00')
    await page.getByLabel('结束时间', { exact: true }).fill('2027-01-10T10:00')
    await page.getByLabel('迟到允许时间（分钟）').fill('10')
    await page.getByLabel('最早交卷时间（分钟）').fill('15')
    await saveModal('保存考试')
    await visible(heading('Java基础测试'))
    examUrl = page.url()
    await button('编辑考试').click()
    await page.getByLabel('考试说明').fill('Java 基础知识与 JWT 认证原理。教师端真实演示试卷。')
    await saveModal('保存考试')
    console.log('PASS draft exam create/edit and rules')

    await singleQuestion('Java中哪个是入口方法？')
    await singleQuestion('阶段4临时题目删除验证')
    const temporary = page.locator('.question-card').filter({ has: heading('阶段4临时题目删除验证') })
    await temporary.getByRole('button', { name:'删除题目', exact:true }).click()
    await temporary.waitFor({ state: 'hidden' })

    await button('+ 添加题目').click()
    await page.getByLabel('题目类型').selectOption('SHORT_ANSWER')
    await page.getByLabel('分值', { exact:true }).fill('10')
    await page.getByLabel('题目内容').fill('请说明JWT认证流程。')
    await page.getByLabel('参考答案', { exact:true }).fill('服务端验证身份后签发Token，客户端携带Token，服务端验证签名和有效期。')
    for (let i=0;i<3;i++) {
      await button('+ 新增评分点').click()
      await page.getByLabel('评分点 ' + (i+1) + ' 内容').fill(['身份认证','Token生成','Token校验'][i])
      await page.getByLabel('评分点 ' + (i+1) + ' 分值').fill(['3','3','4'][i])
    }
    await saveModal('保存题目')
    await visible(heading('请说明JWT认证流程。'))
    const shortCard = page.locator('.question-card').filter({ has: heading('请说明JWT认证流程。') })
    await shortCard.getByRole('button', { name:'编辑题目',exact:true }).click()
    await page.getByLabel('评分点 1 内容').fill('身份认证与JWT作用')
    await page.getByRole('button', { name:'下移',exact:true }).first().click()
    await page.getByRole('button', { name:'上移',exact:true }).nth(1).click()
    await button('+ 新增评分点').click()
    await page.getByRole('button', { name:'移除评分点',exact:true }).last().click()
    await saveModal('保存题目')
    await visible(shortCard.getByText('身份认证与JWT作用', { exact:false }))
    assert.equal(await page.locator('.question-card').count(), 2)
    assert.match(await page.locator('.workspace-content').innerText(), /共 2 题 · 总分 15 分/)
    assert.equal(await shortCard.locator('li').count(), 3)
    console.log('PASS single/short questions, 3 points, edit/reorder/delete, question totals')

    await page.reload()
    await visible(heading('Java基础测试'))
    await visible(heading('请说明JWT认证流程。'))
    assert.equal(await page.locator('.question-card').count(),2)
    await page.screenshot({ path: path.join(output,'exam-draft.png'), fullPage:true })
    await button('发布考试').click()
    await visible(page.getByText('考试发布成功', { exact:true }))
    assert.equal(await button('编辑考试').count(),0)
    assert.equal(await button('+ 添加题目').count(),0)
    assert.equal(await button('编辑题目').count(),0)
    await page.reload()
    await visible(page.getByText(/考试已发布，关键规则和题目已锁定/))
    await page.screenshot({ path: path.join(output,'exam-published.png'), fullPage:true })
    console.log('PASS publish confirmation, PUBLISHED persistence and editing locks')
    }

    await page.goto(courseUrl)
    await visible(heading('Java程序设计'))
    await visible(page.getByText('Java基础测试', { exact:true }))
    await page.goto(base+'/teacher/exams')
    await visible(heading('考试管理'))
    await visible(page.getByText('Java基础测试', { exact:true }))
    await page.goto(base+'/teacher')
    await visible(heading('教师工作台'))
    await visible(page.getByRole('link', { name: /Java程序设计/ }))
    await page.screenshot({ path: path.join(output,'teacher-dashboard.png'), fullPage:true })
    await page.setViewportSize({width:1366,height:768})
    await page.screenshot({path:path.join(output,'teacher-laptop.png'),fullPage:true})
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth),false)
    console.log('PASS dashboard, exam list and laptop layout')
    await page.locator('.workspace-header').getByRole('button', {name:'退出登录'}).click()
    await visible(button('登录'))
    await login('student_demo_1')
    await visible(heading('学生工作台'))
    await page.reload()
    await visible(heading('学生工作台'))
    await page.locator('.workspace-header').getByRole('button', {name:'退出登录'}).click()
    await visible(button('登录'))
    console.log('PASS student login/refresh/logout regression')
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({result:'PASS',courseUrl,examUrl,browserErrors:errors},null,2))
  } catch(e) {
    await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{})
    console.error(e.message)
    console.error(JSON.stringify(errors))
    process.exitCode=1
  } finally {
    await browser.close()
  }
})()
